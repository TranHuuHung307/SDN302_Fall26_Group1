const express = require("express");
const controller = require("../controllers/order");
const { authenticate } = require("../middleware/auth");
const { allowRoles } = require("../middleware/auth");
const router = express.Router();
router.use("/orders", authenticate);
router.post("/orders", controller.checkout);
router.post("/orders/checkout", controller.checkout);
router.get("/orders", controller.listOrders);
router.get("/orders/:id", controller.getOrder);
router.post("/orders/:id/pay", controller.payOrder);
router.post("/orders/:id/pay-simulate", controller.payOrder);
router.patch("/orders/:id/pay", controller.payOrder);
router.patch("/orders/:id/cancel", controller.cancelOrder);
router.post("/orders/:id/cancel", controller.cancelOrder);
router.patch("/orders/:id/status", controller.updateOrderStatus);
const shopOrderRoles = [authenticate, allowRoles("ADMIN", "SHOP_OWNER", "STAFF")];
router.get(["/myshop/orders", "/shop/orders"], shopOrderRoles, controller.listShopOrders);
router.get(["/myshop/orders/:id", "/shop/orders/:id"], shopOrderRoles, controller.getShopOrder);
const confirmOrder = (req, res, next) => { req.body = { ...req.body, orderStatus: "CONFIRMED" }; next(); };
const cancelShopOrder = (req, res, next) => { req.body = { ...req.body, orderStatus: "CANCELLED" }; next(); };
router.patch(["/myshop/orders/:id/confirm", "/shop/orders/:id/confirm"], shopOrderRoles, confirmOrder, controller.updateOrderStatus);
router.patch(["/myshop/orders/:id/status", "/shop/orders/:id/status"], shopOrderRoles, controller.updateOrderStatus);
router.patch(["/myshop/orders/:id/cancel", "/shop/orders/:id/cancel"], shopOrderRoles, cancelShopOrder, controller.updateOrderStatus);
module.exports = router;
